"""Generates src/ui/gallery.ts: cover photos (Unsplash licence, served by picsum.photos) with tiny bundled previews."""
import base64, json
cats = json.load(open('/data/picsum/cats.json'))
authors = {x['id']: x['author'] for x in json.load(open('/data/picsum/list.json'))}
labels = {'nature': 'Natura', 'water': 'Acqua e mare', 'sky': 'Cielo e montagne', 'abstract': 'Texture e astratti', 'city': 'Città e architettura',
          'writing': 'Scrivania e lavoro', 'art': 'Arte e colore', 'flowers': 'Fiori e piante', 'seasons': 'Stagioni', 'food': 'Cibo e caffè'}
order = ['nature', 'water', 'sky', 'flowers', 'seasons', 'city', 'writing', 'abstract', 'art', 'food']
out = ['// Generated by scripts/gen_gallery.py. Photos: Unsplash licence (free to use), delivered by picsum.photos.',
       '// The previews below are tiny bundled WebP images, so browsing the gallery makes no network request;',
       '// the full photo is downloaded only when the user picks it.', '',
       'export interface CoverPhoto {\n\tid: number;\n\tauthor: string;\n\tthumb: string;\n}', '',
       'export interface PhotoCategory {\n\tid: string;\n\tlabel: string;\n\tphotos: CoverPhoto[];\n}', '',
       'export const PHOTO_CATEGORIES: PhotoCategory[] = [']
seen = set()
for c in order:
    out.append(f"\t{{ id: '{c}', label: '{labels[c]}', photos: [")
    for i in cats[c]:
        if i in seen: continue
        seen.add(i)
        b = base64.b64encode(open(f'/data/picsum/sel/{i}.webp', 'rb').read()).decode()
        a = authors[str(i)].replace("'", "\\'")
        out.append(f"\t\t{{ id: {i}, author: '{a}', thumb: 'data:image/webp;base64,{b}' }},")
    out.append('\t] },')
out.append('];')
open('src/ui/gallery.ts', 'w').write('\n'.join(out) + '\n')
print(len(seen))
