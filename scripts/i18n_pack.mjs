// Builds src/i18n/packs.ts from i18n/<lang>.json (+ optional i18n/<lang>.fix.json overrides).
// Each language is stored as a plain array of strings (readable, no compression or encoding).
import fs from 'fs';
const LANGS = ['en', 'es', 'de', 'fr', 'ar', 'ru', 'zh', 'ja'];
const src = JSON.parse(fs.readFileSync('i18n/source.json', 'utf8'));
const ph = (s) => (s.match(/\{\d\}/g) ?? []).sort().join();
const MOMENT = /YYYY|MMMM|MM|DD|dddd|gggg|ww|HH|mm/g;
const mt = (s) => (s.match(MOMENT) ?? []).sort().join();
const read = (f) => (fs.existsSync(f) ? JSON.parse(fs.readFileSync(f, 'utf8')) : {});
const all = read('i18n/all.fix.json');
// Terminology fixes for common machine-translation slips (cryptographic "key", not a door key).
const TERMS = { zh: [[/钥匙/g, '密钥']], es: [[/llave/g, 'clave'], [/Llave/g, 'Clave']] };
const pack = (arr) => arr;
const packs = { it: pack(src) };
let missing = 0;
let EN = {};
for (const l of LANGS) {
	const base = JSON.parse(fs.readFileSync(`i18n/${l}.json`, 'utf8'));
	const fix = { ...all, ...read(`i18n/${l}.fix.json`) };
	const arr = src.map((s) => {
		let t = fix[s] ?? base[s];
		if (t != null && !(s in fix) && /^[\w\s,.:\-/()[\]]*$/.test(s) && mt(s) && mt(t) !== mt(s)) t = s; // date formats stay intact
		if (t == null) { missing++; t = EN[s] ?? s; } // fall back to English
		t = t.replace(/[\u200b-\u200d\ufeff]/g, ''); // zero-width characters added by machine translation
		for (const [re, to] of TERMS[l] ?? []) t = t.replace(re, to);
		if (ph(t) !== ph(s)) throw new Error(`${l}: placeholders differ in "${s}" → "${t}"`);
		return (l === 'en' ? t === s : t === EN[s]) ? '' : t;
	});
	if (l === 'en') EN = Object.fromEntries(src.map((s, i) => [s, arr[i] || s]));
	packs[l] = pack(arr);
}
const body = Object.entries(packs).map(([l, p]) => `\t${l}: ${JSON.stringify(p)},`).join('\n');
const out = `// Generated by scripts/i18n_pack.mjs — do not edit. Sources: i18n/*.json\n// One array per language, same order as the Italian source; '' means "same as English".\nexport const PACKS: Record<string, string[]> = {\n${body}\n};\n`;
fs.writeFileSync('src/i18n/packs.ts', out);
console.log('packs.ts', out.length, 'bytes; missing', missing, Object.entries(packs).map(([l, p]) => `${l}:${JSON.stringify(p).length}`).join(' '));
